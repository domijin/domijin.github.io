#!/usr/bin/env python3
"""Restore Google Analytics 4 coverage on the static pages that lack it.

The legacy Pelican pages carry a gtag.js snippet (measurement ID
G-MWRTXBB8DD). The regenerated book pages under articles/ were written
without one, so the essays that replace the old archive were invisible to
analytics. This script injects the same snippet before </head> in every
target page that does not already have it.

Idempotent: pages that already contain the measurement ID are left alone.

Usage:
  python3 scripts/add-ga4.py [root_dir]
"""
import pathlib
import sys

MEASUREMENT_ID = "G-MWRTXBB8DD"

SNIPPET = f"""  <!-- Google tag (gtag.js) -->
  <script async src="https://www.googletagmanager.com/gtag/js?id={MEASUREMENT_ID}"></script>
  <script>
    window.dataLayer = window.dataLayer || [];
    function gtag(){{dataLayer.push(arguments);}}
    gtag('js', new Date());
    gtag('config', '{MEASUREMENT_ID}');
  </script>
"""

# Directories whose pages are generated by the Next.js export; the root
# layout already carries the tag, so they are not touched here.
SKIP_DIRS = {"_next", "next", "node_modules", ".git", "classic", "out"}


def target_pages(root: pathlib.Path):
    articles = root / "articles"
    if articles.is_dir():
        yield from sorted(articles.rglob("*.html"))


def main():
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    added, skipped = [], []
    for path in target_pages(root):
        text = path.read_text(encoding="utf-8")
        if MEASUREMENT_ID in text:
            skipped.append(path)
            continue
        if "</head>" not in text:
            print(f"  SKIP (no </head>): {path}")
            continue
        text = text.replace("</head>", f"{SNIPPET}</head>", 1)
        path.write_text(text, encoding="utf-8")
        added.append(path)

    print(f"measurement id: {MEASUREMENT_ID}")
    print(f"pages updated : {len(added)}")
    for path in added:
        print(f"  + {path.relative_to(root)}")
    print(f"already tagged : {len(skipped)}")


if __name__ == "__main__":
    main()
