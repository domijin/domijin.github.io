/**
 * Precompute the embeddings for the knowledge nodes.
 *
 * The browser only ever has to embed the *prompt*; the nodes are embedded
 * here, once, and ship as a few kilobytes of vectors. That keeps the
 * download to the visitor at one small model and one forward pass.
 *
 *   node green-app/scripts/embed-nodes.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { pipeline } from "@huggingface/transformers";

const APP = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const NODES_PATH = path.join(APP, "src/data/knowledgeNodes.json");
const OUT_PATH = path.join(APP, "src/data/nodeEmbeddings.ts");

const MODEL = "Xenova/all-MiniLM-L6-v2";
const DIM = 384;

/** The text that represents a node to the embedding model. The description
 *  carries the meaning; the keywords catch the surface vocabulary. */
function textFor(node) {
  return `${node.label}. ${node.description} ${node.keywords.join(", ")}`;
}

const nodes = JSON.parse(fs.readFileSync(NODES_PATH, "utf8"));

console.log(`embedding ${nodes.length} nodes with ${MODEL} …`);

const extractor = await pipeline("feature-extraction", MODEL, {
  dtype: "q8",
  device: "cpu",
});

const texts = nodes.map(textFor);
const output = await extractor(texts, { pooling: "mean", normalize: true });

const rows = [];
for (let i = 0; i < nodes.length; i++) {
  const v = output[i];
  const data = Array.from(v.data);
  if (data.length !== DIM) throw new Error(`expected ${DIM} dims, got ${data.length}`);
  // Round to 4 decimals: the vectors ship as text, and a cosine similarity
  // does not need more precision than that.
  rows.push({ id: nodes[i].id, v: data.map((x) => Math.round(x * 10000) / 10000) });
}

const body = rows
  .map((r) => `  "${r.id}": [\n${r.v.map((x) => `    ${x},`).join("\n")}\n  ],`)
  .join("\n");

const file = `/**
 * Embeddings for the knowledge nodes, precomputed with ${MODEL}
 * (mean pooling, L2-normalised, 4 decimal places).
 *
 * Generated by scripts/embed-nodes.mjs — do not edit by hand.
 * The browser embeds only the prompt and compares it against these.
 */
export const NODE_EMBEDDINGS: Record<string, number[]> = {
${body}
};

export const EMBEDDING_MODEL = "${MODEL}";
export const EMBEDDING_DIM = ${DIM};
`;

fs.writeFileSync(OUT_PATH, file, "utf8");
const size = fs.statSync(OUT_PATH).size;
console.log(`wrote ${OUT_PATH} — ${rows.length} nodes, ${(size / 1024).toFixed(1)} KB`);
